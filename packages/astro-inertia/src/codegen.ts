import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import type { JSONSchema4 } from "json-schema";
import { compile } from "json-schema-to-typescript";

const BANNER = "// Generated by astro-inertia from an Inertia JSON Schema. Do not edit.";

export async function loadSchema(source: string, root: string): Promise<JSONSchema4> {
  if (/^https?:\/\//.test(source)) {
    const response = await fetch(source, { headers: { accept: "application/schema+json, application/json" } });
    if (!response.ok) throw new Error(`astro-inertia: schema ${source} answered ${response.status}`);
    return (await response.json()) as JSONSchema4;
  }
  return JSON.parse(await readFile(resolve(root, source), "utf8")) as JSONSchema4;
}

/**
 * Turns a schema whose `properties` are component names (each value the
 * component's props schema) into a declaration file that fills in
 * astro-inertia's InertiaPages interface.
 */
export async function generateTypes(schema: JSONSchema4): Promise<string> {
  if (schema.type !== "object" || typeof schema.properties !== "object") {
    throw new Error("astro-inertia: the schema must be an object schema whose properties are component names");
  }
  const required = Object.keys(schema.properties);
  // A root title would rename the interface; the name is fixed.
  const { title: _title, ...root } = schema;
  const compiled = await compile({ ...root, required, additionalProperties: false }, "InertiaPagesSchema", {
    bannerComment: "",
    additionalProperties: false,
    strictIndexSignatures: true,
    format: false,
  });
  return [
    BANNER,
    'import "astro-inertia";',
    "",
    compiled.trim(),
    "",
    'declare module "astro-inertia" {',
    "  // eslint-disable-next-line @typescript-eslint/no-empty-object-type",
    "  interface InertiaPages extends InertiaPagesSchema {}",
    "}",
    "",
  ].join("\n");
}

/** Writes the declaration file if its content changed. Returns true when it wrote. */
export async function writeTypes(source: string, output: string, root: string): Promise<boolean> {
  const content = await generateTypes(await loadSchema(source, root));
  const target = resolve(root, output);
  const current = await readFile(target, "utf8").catch(() => undefined);
  if (current === content) return false;
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, content);
  return true;
}
